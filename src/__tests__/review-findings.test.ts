import { describe, it, expect } from "vitest";
import {
  ContingencyEngine,
  createObserver,
  createProject,
  addDependency,
  addTask,
  advanceState,
  transitionState,
  updateTaskState,
  GateBlockedError,
  InvalidStateTransitionError,
  ValidationError,
  type Dependency,
  type LogicGate,
} from "../index.js";

// Regressions for defects found in adversarial review of the 2.0 rewrite.

const dep = (id: string, over: Partial<Dependency> = {}): Dependency => ({
  id, name: id.toUpperCase(), priority: "required", state: "complete", ...over,
});

function readyToShip(): ContingencyEngine {
  const e = new ContingencyEngine({ id: "p", name: "P" });
  e.addDependency(dep("a")).addDependency(dep("b", { priority: "optional", state: "identified" }));
  e.passEntryGate().startBuilding();
  e.addTask({ id: "t", name: "T", state: "pending", reactions: [] }).generateShadowTasks();
  e.updateReactionState("t", { dependencyId: "a" }, "complete").updateTaskState("t", "complete");
  return e;
}

const taskBlock: LogicGate = {
  id: "late", name: "Late block", enabled: true,
  condition: { subject: "b", property: "state", operator: "eq", value: "identified" },
  action: { type: "block", target: "t", message: "b must be past identified" },
};

describe("task-blocking gate triggered after the task completed", () => {
  it("blocks exit", () => {
    const e = readyToShip().addLogicGate(taskBlock);
    expect(() => e.submitForReview()).toThrow(/complete while blocked/);
  });

  it("blocks exit for tasks completed in the constructor config", () => {
    const e = new ContingencyEngine({
      id: "p", name: "P",
      dependencies: [dep("a"), dep("b", { priority: "optional", state: "identified" })],
      tasks: [{ id: "t", name: "T", state: "complete", reactions: [{ id: "r", dependencyId: "a", description: "", state: "complete" }] }],
      logicGates: [taskBlock],
    });
    e.passEntryGate().startBuilding();
    expect(() => e.submitForReview()).toThrow(GateBlockedError);
  });
});

describe("exit criteria judge the resulting state", () => {
  it("a block gate keyed on the target state stops the transition", () => {
    const e = readyToShip().submitForReview();
    e.addLogicGate({ id: "g", name: "No completing", enabled: true,
      condition: { subject: "project", property: "state", operator: "eq", value: "complete" },
      action: { type: "block", target: "project" } });
    expect(() => e.markComplete()).toThrow(GateBlockedError);
    expect(e.getProject().state).toBe("review");
  });

  it("a task generated by the transition itself must be addressed first", () => {
    const e = readyToShip();
    e.addLogicGate({ id: "g", name: "Audit on review", enabled: true,
      condition: { subject: "project", property: "state", operator: "eq", value: "review" },
      action: { type: "generate_task", task: { id: "audit", name: "Audit" } } });
    expect(() => e.submitForReview()).toThrow(/Audit/);
    expect(e.getProject().tasks.map((t) => t.id)).toEqual(["t"]);
  });
});

describe("pure API", () => {
  it("advanceState enforces entry and exit; transitionState is the documented unguarded primitive", () => {
    let p = addDependency(createProject({ id: "p", name: "P" }), dep("a", { state: "undefined" }));
    expect(() => advanceState(p, "gated")).toThrow(GateBlockedError);
    p = transitionState(transitionState(p, "gated"), "building");
    p = addTask(p, { id: "t", name: "T", state: "complete", reactions: [] });
    expect(() => advanceState(p, "review")).toThrow(GateBlockedError);
  });

  it("updateTaskState refuses to complete a blocked task", () => {
    let p = createProject({ id: "p", name: "P", dependencies: [dep("a"), dep("b", { priority: "optional", state: "identified" })] });
    p = addTask(p, { id: "t", name: "T", state: "pending", reactions: [] });
    p = { ...p, logicGates: [taskBlock] };
    expect(() => updateTaskState(p, "t", "complete")).toThrow(GateBlockedError);
  });
});

describe("input integrity", () => {
  it("validates the stored copy, so getters cannot swap values after validation", () => {
    let n = 0;
    const sneaky = { id: "d", name: "D", priority: "required", get state() { return n++ === 0 ? "verified" : "bogus"; } };
    const e = new ContingencyEngine({ id: "p", name: "P" });
    try {
      e.addDependency(sneaky as unknown as Dependency);
    } catch {
      /* rejecting is also acceptable */
    }
    for (const d of e.getProject().dependencies) expect(d.state).not.toBe("bogus");
  });

  it("rejects non-cloneable input with a ValidationError", () => {
    const e = new ContingencyEngine({ id: "p", name: "P" });
    expect(() => e.addDependency({ ...dep("a"), extra: () => 1 } as unknown as Dependency)).toThrow(ValidationError);
  });

  it("rejects a malformed reaction selector", () => {
    const e = readyToShip();
    expect(() => e.updateReactionState("t", null as never, "complete")).toThrow(ValidationError);
  });
});

describe("audit log honesty", () => {
  it("no-op updates are neither committed nor logged", () => {
    const e = readyToShip().addLogicGate({ ...taskBlock, id: "x", enabled: false });
    const before = e.getProject();
    const n = e.getEvents().length;
    e.generateShadowTasks().setLogicGateEnabled("x", false).updateTaskState("t", "complete").updateDependencyState("a", "complete");
    expect(e.getProject()).toBe(before);
    expect(e.getEvents()).toHaveLength(n);
  });

  it("named transitions are bound to their source state", () => {
    const e = readyToShip().submitForReview().markComplete();
    expect(() => e.submitForReview()).toThrow(InvalidStateTransitionError);
    expect(e.getProject().state).toBe("complete");
  });

  it("listeners cannot re-enter the engine and scramble the log", () => {
    const errors: unknown[] = [];
    const observer = createObserver({ onListenerError: (err) => errors.push(err) });
    const e = new ContingencyEngine({ id: "p", name: "P" }, { observer });
    e.subscribe((ev) => {
      if (ev.type === "dependency_added" && ev.subject === "a") e.addDependency(dep("nested"));
    });
    e.addDependency(dep("a"));
    expect(errors).toHaveLength(1);
    expect(String(errors[0])).toMatch(/Re-entrant/);
    expect(e.getProject().dependencies.map((d) => d.id)).toEqual(["a"]);
  });
});
